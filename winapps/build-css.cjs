// Builds dist/winapps.css from the Meridian IAM Range stylesheets: the rules of the copied apps
// (.tm-*, .cp-*, .calc*, .mm-*, .fx-*), its Fluent tokens scoped to the apps, and a few shared
// classes (.mdl, .btn, .input, .muted, table.grid) scoped under .wa so CORP Desk is untouched.
const fs = require('fs'), path = require('path');
const SRC = process.argv[2];
const files = ['styles.css', 'shell.css', 'calculator.css'].map((f) => fs.readFileSync(path.join(SRC, f), 'utf8'));
const OWN = /^(?:\.(?:tm|cp|calc|mm|fx)(?:-[\w-]+)?)(?=$|[\s.:#\[>+~(])/;
const SHARED = /^(?:\.mdl|\.btn|\.input|\.muted|table\.grid)(?=$|[\s.:#\[>+~(])/;
function rules(css) {
  const out = []; let i = 0;
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  while (i < css.length) {
    const open = css.indexOf('{', i); if (open < 0) break;
    const sel = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    out.push({ sel, body: css.slice(open + 1, j - 1).trim() });
    i = j;
  }
  return out;
}
const keep = [];
for (const css of files) for (const r of rules(css)) {
  if (r.sel.startsWith('@')) continue;
  const sels = r.sel.split(',').map((s) => s.trim()).filter(Boolean);
  if (sels.every((s) => OWN.test(s))) keep.push(`${sels.join(',')}{${r.body}}`);
  else if (sels.every((s) => SHARED.test(s))) keep.push(`${sels.map((s) => `.wa ${s},.mm-shield ${s}`).join(',')}{${r.body}}`);
}
const root = rules(files[0].replace(/\/\*[\s\S]*?\*\//g, '')).find((r) => r.sel === ':root').body;
const dark = rules(files[0]).find((r) => r.sel === ":root[data-theme='dark']").body;
const out = `/* Generated by winapps/build-css.cjs from the Meridian IAM Range (styles.css, shell.css, calculator.css). */
.wa,.mm-shield,.cm{${root}}
body.settings-dark .wa,body.settings-dark .mm-shield,body.settings-dark .cm{${dark}}
.wa{height:100%;display:flex;flex-direction:column;min-height:0;background:var(--win-bg);color:var(--ink);font:14px/1.43 var(--font)}
.wa>*{flex:1;min-height:0}
:where(.wa,.mm-shield) *{box-sizing:border-box}
:where(.wa,.mm-shield) :where(button,input,select){font:inherit;color:inherit}
:where(.wa) h2{font:600 20px/28px var(--font-display);margin:0 0 12px}
.cm{position:fixed;z-index:100000;min-width:200px;padding:4px;border-radius:8px;background:var(--layer);border:1px solid var(--line);box-shadow:var(--shadow-soft);font:13px var(--font);color:var(--ink)}
.cm-item{display:flex;align-items:center;gap:8px;width:100%;padding:6px 10px;border:0;border-radius:4px;background:transparent;text-align:left;color:var(--ink)}
.cm-item:hover:not(:disabled){background:var(--hover)}.cm-item:disabled{opacity:.45}
.cm-check{width:14px;text-align:center}.cm-sep{height:1px;margin:4px 6px;background:var(--line)}
${keep.join('\n')}
`;
fs.writeFileSync(path.join(__dirname, '..', 'dist', 'winapps.css'), out);
console.log(`dist/winapps.css: ${keep.length} rules`);
